#!/bin/sh
# Athorize container entrypoint.
#
#  1. Makes sure the data volume is writable by the (non-root) app user.
#  2. Generates SECRET_KEY + the audit-log HMAC key ONCE and persists them in
#     the data volume, so sessions and the hash-chained audit log survive
#     container restarts, re-creates and image upgrades. Env vars override.
#  3. On a blank instance, creates the one-time first-run setup token and
#     prints it prominently (on every start until setup is completed).
#  4. In demo mode, prints a loud "default passwords" warning.
#  5. execs uvicorn (PID 1 handoff, so `docker stop` shuts down cleanly).
#
# POSIX sh (the image's /bin/sh is dash).
set -eu

DATA_DIR="${DATA_DIR:-/data}"
EVIDENCE_DIR="${EVIDENCE_DIR:-$DATA_DIR/evidence}"
BACKUP_DIR="${BACKUP_DIR:-$DATA_DIR/backups}"
export DATA_DIR EVIDENCE_DIR BACKUP_DIR
SECRETS_FILE="$DATA_DIR/secrets.env"
TOKEN_FILE="$DATA_DIR/setup-token"
PORT="${PORT:-8001}"

rule() { echo "=========================================================================="; }

# --- 1. Writable data volume ------------------------------------------------
if ! mkdir -p "$DATA_DIR" "$EVIDENCE_DIR" "$BACKUP_DIR" 2>/dev/null || ! [ -w "$DATA_DIR" ]; then
  rule
  echo " ERROR: $DATA_DIR is not writable by the container user (uid $(id -u))."
  echo " Use the named volume from docker-compose.yml, or if you bind-mount a"
  echo " host folder, give it to uid $(id -u) first:"
  echo "     sudo chown -R $(id -u):$(id -g) /path/on/host"
  rule
  exit 1
fi
umask 077

# --- 2. Persistent secrets --------------------------------------------------
# The audit key's name is ATHORIZE_AUDIT_HMAC_KEY. The names used before
# 2026-10 (UNIVERSAL_AUDIT_HMAC_KEY, AUDIT_HMAC_KEY) are accepted, in the
# environment and in an existing secrets.env, so upgraded volumes keep their key.
for OLD in UNIVERSAL_AUDIT_HMAC_KEY AUDIT_HMAC_KEY; do
  eval "OLDVAL=\${$OLD:-}"
  if [ -n "$OLDVAL" ]; then
    echo "athorize: $OLD is deprecated; rename it to ATHORIZE_AUDIT_HMAC_KEY (the old name still works for now)."
    if [ -z "${ATHORIZE_AUDIT_HMAC_KEY:-}" ]; then ATHORIZE_AUDIT_HMAC_KEY="$OLDVAL"; fi
  fi
done
ENV_SECRET_KEY="${SECRET_KEY:-}"
ENV_HMAC_KEY="${ATHORIZE_AUDIT_HMAC_KEY:-}"

file_value() {  # file_value NAME  -> value from $SECRETS_FILE (empty if absent)
  [ -f "$SECRETS_FILE" ] || return 0
  sed -n "s/^$1=//p" "$SECRETS_FILE" | head -n 1
}
gen_key() { python -c 'import secrets; print(secrets.token_hex(32))'; }

FILE_SECRET_KEY="$(file_value SECRET_KEY)"
FILE_HMAC_KEY="$(file_value ATHORIZE_AUDIT_HMAC_KEY)"
if [ -z "$FILE_HMAC_KEY" ]; then FILE_HMAC_KEY="$(file_value UNIVERSAL_AUDIT_HMAC_KEY)"; fi
CHANGED=0
if [ -z "$ENV_SECRET_KEY" ] && [ -z "$FILE_SECRET_KEY" ]; then
  FILE_SECRET_KEY="$(gen_key)"; CHANGED=1
fi
if [ -z "$ENV_HMAC_KEY" ] && [ -z "$FILE_HMAC_KEY" ]; then
  FILE_HMAC_KEY="$(gen_key)"; CHANGED=1
fi
if [ "$CHANGED" = 1 ]; then
  {
    echo "# Generated by the Athorize container on first start. KEEP THIS FILE."
    echo "# Losing ATHORIZE_AUDIT_HMAC_KEY makes the existing audit log unverifiable."
    if [ -n "$FILE_SECRET_KEY" ]; then echo "SECRET_KEY=$FILE_SECRET_KEY"; fi
    if [ -n "$FILE_HMAC_KEY" ]; then echo "ATHORIZE_AUDIT_HMAC_KEY=$FILE_HMAC_KEY"; fi
  } > "$SECRETS_FILE.tmp"
  mv "$SECRETS_FILE.tmp" "$SECRETS_FILE"
  echo "athorize: generated persistent secrets -> $SECRETS_FILE"
fi
chmod 600 "$SECRETS_FILE" 2>/dev/null || true
SECRET_KEY="${ENV_SECRET_KEY:-$FILE_SECRET_KEY}"
ATHORIZE_AUDIT_HMAC_KEY="${ENV_HMAC_KEY:-$FILE_HMAC_KEY}"
export SECRET_KEY ATHORIZE_AUDIT_HMAC_KEY
unset AUDIT_HMAC_KEY UNIVERSAL_AUDIT_HMAC_KEY OLD OLDVAL ENV_SECRET_KEY ENV_HMAC_KEY FILE_SECRET_KEY FILE_HMAC_KEY

# --- 3. First-run setup token (blank instances only) ------------------------
# The app (services/setup_token.py) reuses an existing <DATA_DIR>/setup-token
# while no user exists and deletes it once setup completes. Creating it here
# lets us print it on EVERY start until setup is done (the app only logs it
# the first time, and `docker compose down` discards old container logs).
DEMO="${ATHORIZE_DEMO_SEED:-0}"
if [ "$DEMO" != "1" ] && [ -z "${DATABASE_URL:-}" ] && [ ! -f "$TOKEN_FILE" ]; then
  if python - "$DATA_DIR/data.db" <<'PY'
import sqlite3, sys, os
db = sys.argv[1]
if not os.path.exists(db):
    sys.exit(0)                      # brand-new instance -> needs a token
try:
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    has_user = con.execute("SELECT 1 FROM users LIMIT 1").fetchone() is not None
except sqlite3.Error:
    has_user = False                 # schema not created yet
sys.exit(1 if has_user else 0)
PY
  then
    python -c 'import secrets; print(secrets.token_urlsafe(24))' > "$TOKEN_FILE"
    chmod 600 "$TOKEN_FILE"
  fi
fi

if [ "$DEMO" = "1" ]; then
  rule
  echo " DEMO MODE (ATHORIZE_DEMO_SEED=1)"
  echo " This instance is seeded with FAKE data and well-known passwords:"
  echo "   admin/admin, operator/operator, manager/manager, analyst/analyst, ..."
  echo " Anyone who can reach it can log in. Do NOT store real data in it and"
  echo " do NOT expose it beyond your own machine. For a real install use"
  echo " docker-compose.yml (blank instance + Setup screen)."
  rule
elif [ -f "$TOKEN_FILE" ]; then
  rule
  echo " FIRST-RUN SETUP — open Athorize in your browser and paste this token"
  echo " into the Setup screen to create the first administrator account:"
  echo ""
  echo "     SETUP TOKEN:  $(cat "$TOKEN_FILE")"
  echo ""
  echo " (also saved in the data volume at $TOKEN_FILE; it is deleted"
  echo "  automatically once setup is complete)"
  rule
fi

# --- 4. Run -----------------------------------------------------------------
cd /app/backend
if [ "$#" -gt 0 ]; then
  exec "$@"
fi
exec python -m uvicorn main:app --host 0.0.0.0 --port "$PORT" --workers 1
